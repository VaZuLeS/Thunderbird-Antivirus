export function t(lang: Language, key: string, fallback?: string): string {
  const currentLangDict = translations[lang];
  if (currentLangDict && currentLangDict[key]) {
    return currentLangDict[key];
  }
  const enDict = translations.en;
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
}
