const esc = (s) =>
  String(s).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
function reviewHtml(input, language = "en") {
  need(Object.hasOwn(labels, language), "CAPACITY_LANGUAGE_INVALID");
  const r = project(input),
    l = labels[language],
    nonce = crypto.randomBytes(18).toString("base64"),
    number = (n) =>
      new Intl.NumberFormat(language, { maximumFractionDigits: 2 }).format(n);
  const value = (m, n) =>
    n === null ? l.not_measured : number(n) + " " + l[m.unit];
  const pair = (label, v) => `<dt>${esc(label)}</dt><dd>${esc(v)}</dd>`;
  const cards = r.metrics
    .map(
      (m) =>
        `<article><h2>${esc(l[m.id])}</h2><p class="badge ${m.state}">${esc(l[m.state])}</p><dl>${pair(l.used, value(m, m.used))}${pair(l.limit, value(m, m.limit))}${pair(l.remaining, value(m, m.remaining))}${pair(l.utilization, m.utilizationBasisPoints === null ? l.not_measured : number(m.utilizationBasisPoints / 100) + " %")}${pair(l.basis, l[m.basis])}</dl></article>`,
    )
    .join("");
  return decorateHTML(`<!doctype html><html lang="${language}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'nonce-${nonce}'; base-uri 'none'; form-action 'none'"><title>Thundy AV · ${esc(l.title)}</title><style nonce="${nonce}">:root{color-scheme:light dark;font:16px/1.6 system-ui,sans-serif}*{box-sizing:border-box}body{margin:0;background:var(--bg-color);color:var(--text-color)}main{max-width:1080px;margin:auto;padding:clamp(16px,4vw,40px)}header,footer,article{background:var(--card-bg);border:1px solid var(--card-border);border-radius:16px;padding:20px;margin:16px 0}header{border-top:5px solid var(--link-color)}.brand{font-weight:800;letter-spacing:.1em;color:var(--link-color)}h1{font-size:clamp(24px,4vw,36px);line-height:1.2}h2{font-size:21px}p,h1,h2,dd,li{overflow-wrap:anywhere}dl{display:grid;grid-template-columns:minmax(0,1fr) minmax(0,1.3fr);gap:8px 18px}dt{font-weight:650}dd{min-width:0;margin:0}.metrics{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:16px}.metrics article{margin:0}ul{display:flex;flex-wrap:wrap;gap:10px;padding:0;list-style:none}li,.badge{border-radius:8px;padding:6px 12px;background:var(--input-bg)}.badge{display:inline-block;font-weight:700}.warning{background:var(--warning-bg);color:var(--color-warning)}.reached{background:var(--alert-error-bg);color:var(--color-danger)}.below{background:var(--input-bg);color:var(--link-color)}.not_measured{background:var(--input-bg);color:var(--text-color)}footer{font-size:14px}@media(prefers-color-scheme:dark){body{background:var(--bg-color);color:var(--text-color)}header,article,footer{background:var(--card-bg);border-color:var(--card-border)}li{background:var(--input-bg)}.brand{color:var(--link-color)}}@media(max-width:700px){.metrics{grid-template-columns:minmax(0,1fr)}dl{display:block}dd{margin-bottom:10px}header,article,footer{padding:16px}}@media print{body,header,article,footer{background:white;color:black}main{padding:0}.metrics{display:block}article{break-inside:avoid}}</style></head><body><main><header><h1>${esc(l.title)}</h1><p>${esc(l.intro)}</p><p>${esc(l.limits)}</p><dl>${pair(l.time, r.capturedAt)}${pair(l.threshold, r.warningPercent + " %")}</dl><h2>${esc(l.summary)}</h2><ul>${Object.entries(
    r.totals,
  )
    .map(([s, n]) => `<li><strong>${n}</strong> ${esc(l[s])}</li>`)
    .join(
      "",
    )}</ul></header><div class="metrics">${cards}</div><footer><p>${esc(l.proof)}</p><dl>${pair(l.alarmHead, r.references.alarmHead ?? l.notAvailable)}${pair(l.pinLabel, r.pins.alarm ? l.pinned : l.unpinned)}${pair(l.sourceHead, r.references.sourceHead ?? l.notAvailable)}${pair(l.pinLabel, r.pins.source ? l.pinned : l.unpinned)}${pair(l.packageHash, r.references.packageHash ?? l.notAvailable)}${pair(l.pinLabel, r.pins.package === null ? l.notAvailable : r.pins.package ? l.pinned : l.unpinned)}</dl></footer></main></body></html>`, language);
}
