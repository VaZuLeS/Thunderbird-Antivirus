const esc = (s) =>
  String(s).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
function reviewHtml(content, context, language = "en") {
  need(Object.hasOwn(words, language), "CAPACITY_ALERT_LANGUAGE_INVALID");
  const r = CapacityAlerts.verifyJournal(content, context),
    l = words[language],
    m = metrics[language],
    nonce = crypto.randomBytes(18).toString("base64"),
    pair = (k, v) => `<dt>${esc(k)}</dt><dd>${esc(v ?? "—")}</dd>`,
    number = (n) => new Intl.NumberFormat(language).format(n),
    transitions = {
      RAISED: l[3],
      ESCALATED: l[4],
      REMINDER: l[5],
      RECOVERED: l[6],
    },
    refs = (v) =>
      Object.entries(v)
        .map(([k, val]) => pair(m[k], val))
        .join("");
  const candidates = [...r.notifications]
    .reverse()
    .map(
      (n) =>
        `<article><h2>${esc(m[n.metric.id])} · ${esc(transitions[n.transition])}</h2><p class="badge">${esc(n.status === "PENDING" ? l[1] : l[2])}</p><p>${esc(m.used)}: ${number(n.metric.used)} / ${number(n.metric.limit)} · ${esc(m[n.metric.state])}</p><dl>${pair(l[8], n.generatedAt)}${pair(l[9], number(n.suppressedObservations))}${pair(l[10], n.consumerId)}${pair(l[23], n.acknowledgedAt)}</dl><details><summary>${esc(l[24])}</summary><dl>${pair(l[11], n.notificationId)}${refs(n.references)}${pair("SHA-256 (" + m.alarm_bytes + ")", n.inputHashes.alarm)}${pair("SHA-256 (" + m.source_bytes + ")", n.inputHashes.source)}${pair(m.pinLabel + " · " + m.alarmHead, n.pins.alarm ? m.pinned : m.unpinned)}${pair(m.pinLabel + " · " + m.sourceHead, n.pins.source ? m.pinned : m.unpinned)}${pair(m.pinLabel + " · " + m.packageHash, n.pins.package === null ? m.notAvailable : n.pins.package ? m.pinned : m.unpinned)}</dl></details></article>`,
    )
    .join("");
  const current = r.lastObservation
    ? `<p>${esc(r.lastObservation.report.capturedAt)}</p>${r.lastObservation.report.metrics.map((v) => `<p><strong>${esc(m[v.id])}</strong>: ${v.used === null ? esc(m.not_measured) : number(v.used) + " / " + number(v.limit)} · ${esc(m[v.state])} · ${esc(r.metrics.find((x) => x.metric.id === v.id)?.active ? l[21] : l[22])}</p>`).join("")}`
    : `<p>${esc(l[20])}</p>`;
  return decorateHTML(
    `<!doctype html><html lang="${language}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'nonce-${nonce}'; base-uri 'none'; form-action 'none'"><title>Thundy AV · ${esc(l[0])}</title><style nonce="${nonce}">body{margin:0;background:var(--bg-color);color:var(--text-color);font:16px/1.6 system-ui}main{max-width:1080px;margin:auto;padding:clamp(16px,4vw,40px)}header,article,section,footer{background:var(--card-bg);border:1px solid var(--card-border);border-radius:16px;padding:20px;margin:16px 0}h1{font-size:clamp(24px,4vw,36px)}h2{font-size:21px}p,dd,h1,h2{overflow-wrap:anywhere}dl{display:grid;grid-template-columns:minmax(0,1fr) minmax(0,2fr);gap:8px 16px}dd{margin:0;min-width:0}dt{font-weight:650}@media(max-width:700px){dl{display:block}dd{margin-bottom:12px}}</style></head><body><main><header><h1>${esc(l[0])}</h1><p>${esc(l[15])}</p><p>${esc(r.verification.headPinned ? l[13] : l[14])}</p><dl>${pair(l[1], number(r.pending))}${pair(l[2], number(r.acknowledged))}${pair(l[17], (context.warningPercent ?? 80) + " % / " + (context.recoveryPercent ?? 70) + " %")}${pair(l[18], number(context.cooldownMs ?? 900000))}${pair(l[19], number(r.maxPending))}${pair(l[12], r.journalHead)}</dl></header><section><h2>${esc(l[16])}</h2>${current}</section>${candidates || `<p>${esc(l[7])}</p>`}<footer><p>${esc(l[15])}</p></footer></main></body></html>`,
    language,
  );
}
module.exports = { reviewHtml, words };
